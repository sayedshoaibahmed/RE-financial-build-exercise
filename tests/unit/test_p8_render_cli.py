"""P8: `render` (commentary.md + grounding_report.json) and its exit codes."""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

from trend.digest import build_digest
from trend.grounding import tokens_in
from trend.writers.json_out import dumps

ROOT = Path(__file__).resolve().parents[2]
CLI = ROOT / ".claude" / "skills" / "monthly-trend-analysis" / "scripts" / "trend_cli.py"
GOOD = (ROOT / "tests" / "fixtures" / "commentary" / "good_abc_2026-06.md").read_text(encoding="utf-8")
META = {"input_sha256": "0" * 64, "config_sha256": "1" * 64}
RUN = "2026-06_w12-2026-06"


def cli(*args, cwd=ROOT):
    return subprocess.run([sys.executable, str(CLI), *map(str, args)], cwd=cwd, capture_output=True, text=True)


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


@pytest.fixture(scope="module")
def digest_text(abc, abc_metrics, abc_flagset):
    return dumps(build_digest(abc.company, abc_metrics, abc_flagset, abc.mapped, META))


def make_run(base, digest_text, draft=GOOD, name=RUN, company="abc_inc", with_draft=True):
    d = Path(base) / company / name
    d.mkdir(parents=True)
    (d / "digest.json").write_text(digest_text, encoding="utf-8")
    if with_draft:
        (d / "commentary_draft.md").write_text(draft, encoding="utf-8")
    return d


def files(d):
    return sorted(p.name for p in Path(d).iterdir())


# ---------------------------------------------------------------- a grounded draft renders

def test_render_ok_writes_commentary_and_the_report(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    r = cli("render", "--run-dir", run)
    assert r.returncode == 0, r.stderr
    assert files(run) == ["commentary.md", "commentary_draft.md", "digest.json", "grounding_report.json"]
    assert "status: OK" in r.stdout and "commentary.md" in r.stdout and "grounding_report.json" in r.stdout


def test_tokens_are_replaced_by_display_strings_and_the_banner_is_kept(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    cli("render", "--run-dir", run)
    md = (run / "commentary.md").read_text(encoding="utf-8")
    body = md.split("## Audit appendix")[0]
    assert md.startswith("DRAFT — AI-generated from digest.json. Not reviewed. For analyst review.")
    assert "{{" not in body and "}}" not in body
    assert "Revenue was 195,898.16, -5.98% on the prior month." in body
    assert "Dec 2025 operating income was 534,551.41 reported and -375,217.90 adjusted, a difference of -909,769.31." in body
    assert "Gross margin moved 3.11 pp to 70.15%." in body


def test_audit_appendix_lists_every_fact_id_used_with_its_display(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    cli("render", "--run-dir", run)
    md = (run / "commentary.md").read_text(encoding="utf-8")
    assert md.count("## Audit appendix") == 1
    rows = re.findall(r"^\| (\S+) \| (.+?) \|$", md.split("## Audit appendix")[1], re.M)
    rows = [r for r in rows if r[0] not in ("Fact", "---")]
    allowed = json.loads(digest_text)["allowed_facts"]
    used = sorted(set(tokens_in(GOOD)))
    assert [r[0] for r in rows] == used                          # every fact id used, once, sorted
    assert all(allowed[fid] == shown for fid, shown in rows)     # the appendix shows exactly the digest's display string
    assert "generated by code" in md.lower()


def test_grounding_report_for_a_pass(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    cli("render", "--run-dir", run)
    rep = json.loads((run / "grounding_report.json").read_text(encoding="utf-8"))
    assert rep["status"] == "OK" and rep["failures"] == []
    assert [c["code"] for c in rep["checks"]] == [f"G{i}" for i in range(1, 11)]
    assert all(c["failures"] == 0 and c["name"] and c["description"] for c in rep["checks"])
    assert rep["draft_sha256"] == sha(run / "commentary_draft.md") and rep["digest_sha256"] == sha(run / "digest.json")
    assert rep["tokens_used"] == len(set(tokens_in(GOOD))) and rep["company_id"] == "abc_inc" and rep["as_of"] == "2026-06"
    assert "deliberately narrow" in rep["notes"]["G4"] and "movements, not causes" in rep["notes"]["G3"]


def test_render_is_byte_identical_on_two_runs(tmp_path, digest_text):
    a, b = make_run(tmp_path / "a", digest_text), make_run(tmp_path / "b", digest_text)
    cli("render", "--run-dir", a)
    cli("render", "--run-dir", b)
    for name in ("commentary.md", "grounding_report.json"):
        assert (a / name).read_bytes() == (b / name).read_bytes(), name
    cli("render", "--run-dir", a)                                # and re-rendering the same folder changes nothing
    assert (a / "commentary.md").read_bytes() == (b / "commentary.md").read_bytes()


def test_render_does_not_touch_the_digest_or_the_draft(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    before = (sha(run / "digest.json"), sha(run / "commentary_draft.md"))
    cli("render", "--run-dir", run)
    assert (sha(run / "digest.json"), sha(run / "commentary_draft.md")) == before


# ---------------------------------------------------------------- a failed draft writes only the report

BAD = GOOD.replace("month on month.", "month on month by 5 points because of fewer fees.").replace(
    "{{rep.opex.total.pct_rev.2026-06}}", "{{rep.opex.total.pct_rev.2030-01}}")


def test_failed_render_exits_4_and_writes_only_the_report(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text, draft=BAD)
    r = cli("render", "--run-dir", run)
    assert r.returncode == 4
    assert files(run) == ["commentary_draft.md", "digest.json", "grounding_report.json"]
    rep = json.loads((run / "grounding_report.json").read_text(encoding="utf-8"))
    assert rep["status"] == "GROUNDING_FAILED"
    assert sorted({f["code"] for f in rep["failures"]}) == ["G1", "G2", "G3"]        # all of them at once
    for f in rep["failures"]:
        assert set(f) == {"code", "name", "message", "line", "text"} and f["message"]
    assert {c["code"]: c["failures"] for c in rep["checks"]}["G2"] == 1
    for code in ("G1", "G2", "G3"):                                                    # the console lists them too
        assert code in r.stderr
    assert "GROUNDING_FAILED" in r.stderr


def test_a_failed_render_removes_a_stale_commentary_from_an_earlier_run(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text)
    assert cli("render", "--run-dir", run).returncode == 0 and (run / "commentary.md").exists()
    (run / "commentary_draft.md").write_text(BAD, encoding="utf-8")
    assert cli("render", "--run-dir", run).returncode == 4
    assert not (run / "commentary.md").exists()
    assert files(run) == ["commentary_draft.md", "digest.json", "grounding_report.json"]
    assert json.loads((run / "grounding_report.json").read_text())["status"] == "GROUNDING_FAILED"
    (run / "commentary_draft.md").write_text(GOOD, encoding="utf-8")                  # and a fixed draft brings it back
    assert cli("render", "--run-dir", run).returncode == 0 and (run / "commentary.md").exists()


def test_the_draft_option_points_at_another_file(tmp_path, digest_text):
    run = make_run(tmp_path, digest_text, with_draft=False)
    elsewhere = tmp_path / "my_draft.md"
    elsewhere.write_text(GOOD, encoding="utf-8")
    assert cli("render", "--run-dir", run).returncode == 2                           # no default draft there
    assert cli("render", "--run-dir", run, "--draft", elsewhere).returncode == 0
    assert (run / "commentary.md").exists()


