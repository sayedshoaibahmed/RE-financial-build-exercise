def test_good_draft_renders_against_the_digest_a_real_cli_run_wrote(real_run):
    (real_run / "commentary_draft.md").write_text(GOOD, encoding="utf-8")
    before = {n: sha(real_run / n) for n in ("digest.json", "metrics.json", "trend_pack.xlsx")}
    r = cli("render", "--company", "abc_inc", "--out", real_run.parent.parent)
    assert r.returncode == 0, r.stderr
    assert (real_run / "commentary.md").exists()
    assert {n: sha(real_run / n) for n in before} == before          # the workbook (and its Commentary sheet) are left alone
    assert "195,898.16" in (real_run / "commentary.md").read_text(encoding="utf-8")
    assert json.loads((real_run / "grounding_report.json").read_text())["status"] == "OK"
