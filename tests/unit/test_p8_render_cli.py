def test_a_blocked_run_cannot_be_rendered(tmp_path):
    d = tmp_path / "abc_inc" / "latest_w12-latest"
    d.mkdir(parents=True)
    (d / "blocked_report.json").write_text(json.dumps({"status": "BLOCKED", "reason": "RECON_FAIL", "message": "RECON_FAIL: 4 control(s) failed"}), encoding="utf-8")
    (d / "commentary_draft.md").write_text(GOOD, encoding="utf-8")
