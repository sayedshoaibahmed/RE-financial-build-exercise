"""Build, compare, print and store the frozen ABC flag list (tests/golden/abc_flags.expected.json).

Used by tests/unit/test_golden_flags.py and scripts/regen_golden_flags.py. The flags are recomputed from the
real workbook through the production code path; only presentation (2 dp strings) is applied here.
"""
import json
from pathlib import Path

import yaml

from trend.adapters.excel_pl import ExcelPLAdapter
from trend.categories import load_vocabulary
from trend.config import load_company
from trend.flags import TYPES, compute_flags
from trend.mapping import load_mapping, map_records
from trend.metrics import compute_metrics
from trend.reconcile import reconcile

ROOT = Path(__file__).resolve().parent.parent
ABC_DIR = ROOT / "companies" / "abc_inc"
GOLDEN = Path(__file__).resolve().parent / "golden" / "abc_flags.expected.json"
FIELDS = ("id", "type", "severity", "period", "subject", "observed", "basis")
WARNING = ("FROZEN LIST. Generated by scripts/regen_golden_flags.py. Regenerating changes what the test accepts, "
           "so a human must review every difference first. Never regenerate just to make a failing test pass.")


def fmt_observed(o):
    if isinstance(o, dict):
        return ", ".join(f"{k}={'none' if v is None else v}" for k, v in o.items())
    return str(o)


def sort_key(f):
    return (f["type"], f["period"], f["subject"], f["basis"])


def current_golden():
    """Recompute the ABC flags and return the structure stored in the golden file."""
    company = load_company(ABC_DIR)
    records, controls = ExcelPLAdapter(company.source, company.company_id).load()
    mapped = map_records(records, load_mapping(ABC_DIR, load_vocabulary()), company, ABC_DIR)
    recon = reconcile(records, controls, company.source, mapped=mapped)
    metrics = compute_metrics(mapped, recon, company)
    fs = compute_flags(mapped, recon, metrics, company)
    flags = sorted(({k: f.to_dict()[k] for k in FIELDS} for f in fs.flags), key=sort_key)
    thresholds = yaml.safe_load((ABC_DIR / "company.yaml").read_text(encoding="utf-8"))["thresholds"]
    return {"_header": {"warning": WARNING, "company": company.company_id,
                        "thresholds_source": "companies/abc_inc/company.yaml",
                        "thresholds": thresholds,
                        "counts": {t: sum(1 for f in flags if f["type"] == t) for t in TYPES},
                        "total": len(flags)},
            "flags": flags}


def _line(f):
    return f"{f['id']} {f['type']} {f['period']} {f['subject']} observed=[{fmt_observed(f['observed'])}] basis={f['basis']}"


def compare(expected, actual):
    """-> list of human-readable differences (empty when identical)."""
    out = []
    eh, ah = expected["_header"], actual["_header"]
    for key in ("thresholds", "counts"):
        for k in sorted(set(eh[key]) | set(ah[key])):
            if eh[key].get(k) != ah[key].get(k):
                out.append(f"HEADER {key} changed: {k}: {eh[key].get(k)!r} -> {ah[key].get(k)!r}")
    if eh["total"] != ah["total"]:
        out.append(f"HEADER total changed: {eh['total']} -> {ah['total']}")
    old = {f["id"]: f for f in expected["flags"]}
    new = {f["id"]: f for f in actual["flags"]}
    for fid in sorted(set(new) - set(old), key=lambda i: sort_key(new[i])):
        out.append("ADDED   " + _line(new[fid]))
    for fid in sorted(set(old) - set(new), key=lambda i: sort_key(old[i])):
        out.append("REMOVED " + _line(old[fid]))
    for fid in sorted(set(old) & set(new), key=lambda i: sort_key(old[i])):
        for field in FIELDS:
            if old[fid][field] != new[fid][field]:
                a, b = old[fid][field], new[fid][field]
                if field == "observed":
                    a, b = f"[{fmt_observed(a)}]", f"[{fmt_observed(b)}]"
                out.append(f"CHANGED {fid} {old[fid]['type']} {old[fid]['period']} {old[fid]['subject']}: "
                           f"{field}: {a} -> {b}")
    return out


def format_table(flags):
    """One line per flag, sorted by type, period, subject: id | type | severity | period | subject | observed | basis."""
    return "\n".join(" | ".join([f["id"], f["type"], f["severity"], f["period"], f["subject"],
                                 fmt_observed(f["observed"]), f["basis"]])
                     for f in sorted(flags, key=sort_key))


def dumps(golden):
    """Header indented, one flag per line, so a diff of the file reads flag by flag."""
    head = json.dumps(golden["_header"], indent=2, ensure_ascii=False)
    body = ",\n".join("    " + json.dumps(f, ensure_ascii=False) for f in golden["flags"])
    return '{\n  "_header": ' + head.replace("\n", "\n  ") + ',\n  "flags": [\n' + body + "\n  ]\n}\n"


def write(golden):
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(dumps(golden), encoding="utf-8")
