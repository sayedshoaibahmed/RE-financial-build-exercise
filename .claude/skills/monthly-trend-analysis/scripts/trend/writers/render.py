"""render: check a DRAFT commentary against digest.json, then replace {{fact id}} tokens with display strings.

Writes commentary.md (with a code-generated audit appendix) and grounding_report.json. If any grounding check fails,
ONLY grounding_report.json is written and a stale commentary.md from an earlier render is deleted.
The draft and the digest are untrusted text: they are parsed (json, regex) and never evaluated or executed.
"""
import hashlib
import json
import re
from dataclasses import dataclass, field
from pathlib import Path

from ..grounding import CHECKS, Failure, check_draft, report_notes, tokens_in
from ..manifest import INTEGRITY, verify_digest
from ..pipeline import EXIT_BLOCKED, EXIT_GROUNDING_FAILED, EXIT_OK, UsageError
from .json_out import write_json

MAX_DRAFT_BYTES = 500_000
MAX_DIGEST_BYTES = 5_000_000
_TOKEN = re.compile(r"\{\{([A-Za-z0-9_.\-]+)\}\}")


@dataclass
class RenderResult:
    status: str                  # OK | GROUNDING_FAILED | BLOCKED
    exit_code: int
    run_dir: Path
    files: list = field(default_factory=list)
    failures: list = field(default_factory=list)
    message: str = ""


def find_latest_run(base, company_id):
    """The newest run folder under <base>/<company_id>/ that holds a digest.json or a blocked_report.json."""
    root = Path(base) / company_id
    found = []
    if root.is_dir():
        for d in root.iterdir():
            for marker in ("digest.json", "blocked_report.json"):
                f = d / marker
                if f.is_file():
                    found.append((f.stat().st_mtime, d.name, d))
    if not found:
        raise UsageError(f"no run folder found for company {company_id!r} under {root}: run `trend_cli.py run` first, "
                         "or pass --run-dir")
    return max(found)[2]


def _sha(b):
    return hashlib.sha256(b).hexdigest()


def render_text(draft, digest, digest_sha=""):
    """The draft with every token replaced by its display string, plus the audit appendix."""
    allowed = digest["allowed_facts"]
    text = draft.replace("\r\n", "\n")
    body = _TOKEN.sub(lambda m: allowed.get(m.group(1), m.group()), text).rstrip("\n") + "\n"
    rows = "".join(f"| {fid} | {allowed[fid]} |\n" for fid in sorted(set(tokens_in(text))) if fid in allowed)
    note = f" (digest.json SHA-256 {digest_sha})" if digest_sha else ""
    return (body + "\n---\n\n## Audit appendix\n\n"
            f"Generated by code from digest.json{note}, not written by the model. Every number above is one of these fact ids.\n\n"
            "| Fact id | Display string |\n|---|---|\n" + rows)


def _read_json(path):
    if path.stat().st_size > MAX_DIGEST_BYTES:
        raise UsageError(f"{path.name} is too large to be a digest")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (ValueError, UnicodeDecodeError) as e:
        raise UsageError(f"{path.name} is not valid JSON: {e}") from None
    return data


def _integrity_failure(run_dir, draft_path, code, message, expected, actual):
    """The digest cannot be trusted: write ONLY grounding_report.json and drop any stale commentary.md."""
    failure = Failure(code, message, None, "digest.json")
    report = {"schema_version": 1, "status": "GROUNDING_FAILED", "company_id": None, "as_of": None,
              "draft_file": draft_path.name, "digest_sha256": actual, "expected_digest_sha256": expected,
              "tokens_used": 0, "checks": [], "failures": [failure.to_dict()],
              "notes": {code: INTEGRITY[code]}}
    report_path = run_dir / "grounding_report.json"
    write_json(report_path, report)
    (run_dir / "commentary.md").unlink(missing_ok=True)
    return RenderResult("GROUNDING_FAILED", EXIT_GROUNDING_FAILED, run_dir, [report_path], [failure],
                        f"{code}: only grounding_report.json was written")


def render_run(run_dir, draft_path=None):
    run_dir = Path(run_dir)
    if not run_dir.is_dir():
        raise UsageError(f"run folder not found: {run_dir}")
    digest_path = run_dir / "digest.json"
    if not digest_path.is_file():
        blocked = run_dir / "blocked_report.json"
        if blocked.is_file():
            info = _read_json(blocked)
            reason = info.get("reason", "BLOCKED") if isinstance(info, dict) else "BLOCKED"
            return RenderResult("BLOCKED", EXIT_BLOCKED, run_dir, [],
                                message=f"this run was BLOCKED ({reason}): there is no digest to check a commentary against")
        raise UsageError(f"digest.json not found in {run_dir}")
    draft_path = Path(draft_path) if draft_path else run_dir / "commentary_draft.md"
    bad = verify_digest(run_dir)                                           # before anything in the digest is trusted
    if bad:
        return _integrity_failure(run_dir, draft_path, *bad)
    if not draft_path.is_file():
        raise UsageError(f"draft not found: {draft_path} (the commentary writer saves it as commentary_draft.md in the run folder)")
    if draft_path.stat().st_size > MAX_DRAFT_BYTES:
        raise UsageError(f"{draft_path.name} is larger than {MAX_DRAFT_BYTES} bytes")
    try:
        draft = draft_path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        raise UsageError(f"{draft_path.name} is not valid UTF-8 text") from None

    digest = _read_json(digest_path)
    if not isinstance(digest, dict) or not isinstance(digest.get("allowed_facts"), dict):
        raise UsageError("digest.json is not a digest (no allowed_facts)")
    if digest.get("status") != "OK":
        return RenderResult("BLOCKED", EXIT_BLOCKED, run_dir, [],
                            message=f"this run's digest has status {digest.get('status')!r}, not OK")

    failures = check_draft(draft, digest)
    digest_sha = _sha(digest_path.read_bytes())
    counts = {}
    for f in failures:
        counts[f.code] = counts.get(f.code, 0) + 1
    report = {"schema_version": 1, "status": "GROUNDING_FAILED" if failures else "OK",
              "company_id": digest.get("company_id"), "as_of": digest.get("as_of"), "draft_file": draft_path.name,
              "draft_sha256": _sha(draft_path.read_bytes()), "digest_sha256": digest_sha,
              "tokens_used": len(set(tokens_in(draft))),
              "checks": [{"code": c, "name": n, "description": d, "failures": counts.get(c, 0)} for c, (n, d) in CHECKS.items()],
              "failures": [f.to_dict() for f in failures], "notes": report_notes()}
    report_path, md_path = run_dir / "grounding_report.json", run_dir / "commentary.md"
    write_json(report_path, report)
    if failures:
        md_path.unlink(missing_ok=True)                                  # never leave an old commentary beside a failed check
        return RenderResult("GROUNDING_FAILED", EXIT_GROUNDING_FAILED, run_dir, [report_path], failures,
                            f"{len(failures)} grounding failure(s); only grounding_report.json was written")
    md_path.write_text(render_text(draft, digest, digest_sha), encoding="utf-8", newline="\n")
    return RenderResult("OK", EXIT_OK, run_dir, [md_path, report_path])
